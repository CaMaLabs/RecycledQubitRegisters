def factor_int(n: int) -> list[int]:
    out = []
    d = 2
    x = int(n)
    while d * d <= x:
        if x % d == 0:
            out.append(d)
            while x % d == 0:
                x //= d
        d += 1 if d == 2 else 2
    if x > 1:
        out.append(x)
    return out


def multiplicative_order_from_lambda(a: int, n: int, lam: int) -> int:
    if math.gcd(a, n) != 1:
        raise ValueError("base must be coprime to N")
    r = int(lam)
    for p in factor_int(r):
        while r % p == 0 and pow(a, r // p, n) == 1:
            r //= p
    if pow(a, r, n) != 1:
        raise AssertionError("order validation failed")
    return r


def factor_witness(a: int, r: int, n: int) -> dict:
    if r <= 0 or r % 2:
        return {"factor_success": False, "x": None, "factors": []}
    x = pow(a, r // 2, n)
    fs = []
    for g in (math.gcd(x - 1, n), math.gcd(x + 1, n)):
        if 1 < g < n and n % g == 0:
            pair = [min(g, n // g), max(g, n // g)]
            if pair not in fs:
                fs.append(pair)
    return {"factor_success": bool(fs), "x": int(x), "factors": fs}


def nontrivial_factor(g: int, n: int):
    return int(g) if 1 < g < n and n % g == 0 else None


def power2_chain_shortcut(base: int, n: int, max_steps: int | None = None) -> dict:
    """Public repeated-squaring/GCD guardrail used by the Dark Star track."""
    if max_steps is None:
        max_steps = max(2, n.bit_length() + 1)

    direct = nontrivial_factor(math.gcd(base, n), n)
    if direct is not None:
        return {"factor_found": True, "factor": direct, "source": "gcd(base,N)"}

    x = base % n
    for k in range(max_steps + 1):
        gm = nontrivial_factor(math.gcd(x - 1, n), n)
        gp = nontrivial_factor(math.gcd(x + 1, n), n)
        if gm is not None or gp is not None:
            return {
                "factor_found": True,
                "factor": gm if gm is not None else gp,
                "source": "power2_chain_gcd",
                "step": int(k),
                "power_exponent": int(1 << k),
            }
        if x == 1:
            return {"factor_found": False, "factor": None, "source": "hit_one"}
        x = (x * x) % n
    return {"factor_found": False, "factor": None, "source": "step_limit"}


def convergent_denominators(num: int, den: int):
    coeffs = []
    n, d = int(num), int(den)
    while d:
        q, rem = divmod(n, d)
        coeffs.append(q)
        n, d = d, rem

    p_nm2, p_nm1 = 0, 1
    q_nm2, q_nm1 = 1, 0
    for coeff in coeffs:
        p = coeff * p_nm1 + p_nm2
        q = coeff * q_nm1 + q_nm2
        if q:
            yield q
        p_nm2, p_nm1 = p_nm1, p
        q_nm2, q_nm1 = q_nm1, q


def nearest_bin_and_probability(s: int, r: int, phase_bits: int) -> tuple[int, float]:
    q = 1 << phase_bits
    scaled = q * s / r
    y_raw = int(math.floor(scaled + 0.5))
    y = y_raw % q
    delta = (s / r) - (y / q)
    delta -= round(delta)

    if abs(delta) < 1e-16:
        return y, 1.0
    den = math.sin(math.pi * delta)
    if abs(den) < 1e-16:
        return y, 1.0
    num = math.sin(math.pi * q * delta)
    p = (num / (q * den)) ** 2
    return y, min(1.0, max(0.0, float(p)))


def fast_recover_from_validation_order(
    y: int, phase_bits: int, r_validation_only: int, n: int
) -> bool:
    """Theorem-equivalent strict scorer used by the residue-prime audits."""
    if y == 0:
        return False
    q = 1 << phase_bits
    seen = set()
    for d in convergent_denominators(y, q):
        d = int(d)
        if d <= 1 or d > n or d in seen:
            continue
        seen.add(d)
        if d % r_validation_only == 0:
            return True
    return False


def per_shot_stage_success(n: int, order: int, phase_bits: int) -> float:
    if (1 << phase_bits) < order:
        return 0.0
    total = 0.0
    cache = {}
    for s in range(order):
        y, p_near = nearest_bin_and_probability(s, order, phase_bits)
        if y not in cache:
            cache[y] = fast_recover_from_validation_order(y, phase_bits, order, n)
        if cache[y]:
            total += p_near / order
    return float(total)


def stage_schedule(n: int, start_bits: int, step_bits: int) -> list[int]:
    cap = 2 * n.bit_length()
    start = max(2, min(int(start_bits), cap))
    step = max(1, int(step_bits))
    vals = list(range(start, cap + 1, step))
    if not vals or vals[-1] != cap:
        vals.append(cap)
    return vals


def expected_stage_shots(p: float, max_shots: int) -> float:
    if p <= 0.0:
        return float(max_shots)
    q = 1.0 - p
    return float((1.0 - q ** max_shots) / p)


# ---- Exact analytic mirror of ibm_shor_generic_arithmetic_clean_mcx.py ----

def mcx_clean_count(controls: int) -> Counter:
    c = Counter()
    k = int(controls)
    if k == 0:
        c["x"] += 1
    elif k == 1:
        c["cx"] += 1
    elif k == 2:
        c["ccx"] += 1
    else:
        # Reusable clean-ancilla linear MCX chain.
        c["ccx"] += 2 * k - 3
    return c


def add_constant_mod_2m_count(m: int, constant: int, external_controls: int) -> Counter:
    c = Counter()
    value = int(constant) % (1 << m)
    for k in range(m):
        if not ((value >> k) & 1):
            continue
        for i in range(m - 1, k, -1):
            c += mcx_clean_count(external_controls + (i - k))
        c += mcx_clean_count(external_controls)
    return c


def add_constant_mod_n_count(
    n_modulus: int, constant: int, external_controls: int
) -> Counter:
    work_bits = (n_modulus - 1).bit_length()
    acc_bits = work_bits + 1
    a = int(constant) % n_modulus
    if a == 0:
        return Counter()

    c = Counter()
    c += add_constant_mod_2m_count(acc_bits, a, external_controls)
    c += add_constant_mod_2m_count(acc_bits, -n_modulus, external_controls)
    c += mcx_clean_count(external_controls + 1)  # sign -> flag
    c += add_constant_mod_2m_count(acc_bits, n_modulus, external_controls + 1)
    c += add_constant_mod_2m_count(acc_bits, -a, external_controls)
    c += mcx_clean_count(external_controls)      # flag toggle
    c += mcx_clean_count(external_controls + 1)  # sign -> flag
    c += add_constant_mod_2m_count(acc_bits, a, external_controls)
    return c


def controlled_modmul_count(n: int, multiplier: int) -> Counter:
    work_bits = (n - 1).bit_length()
    c = int(multiplier) % n
    if math.gcd(c, n) != 1:
        raise ValueError(f"multiplier {c} is not invertible modulo N={n}")

    out = Counter()
    # phase/control + source work bit = two external controls.
    for i in range(work_bits):
        term = (c * (1 << i)) % n
        out += add_constant_mod_n_count(n, term, 2)

    out["cswap"] += work_bits

    inv = pow(c, -1, n)
    for i in range(work_bits):
        term = (inv * (1 << i)) % n
        out += add_constant_mod_n_count(n, -term, 2)
    return out


def arithmetic_width(n: int) -> dict:
    work = (n - 1).bit_length()
    acc = work + 1
    # Existing clean-MCX construction:
    # max controls = 3 + (acc-1), scratch = max_controls-2 = acc.
    scratch = acc
    arithmetic = work + acc + 1 + scratch
    return {
        "work_bits": work,
        "accumulator_bits": acc,
        "flag_bits": 1,
        "clean_mcx_scratch_bits": scratch,
        "arithmetic_qubits_excluding_phase": arithmetic,
        "recycled_logical_qubits": arithmetic + 1,
    }


def stage_arithmetic_count(n: int, base: int, phase_bits: int, cache: dict) -> Counter:
    total = Counter()
    for k in range(phase_bits):
        mult = pow(base, 1 << k, n)
        key = (n, mult)
        if key not in cache:
            cache[key] = controlled_modmul_count(n, mult)
        total += cache[key]
    return total



def stage_arithmetic_count_public_identity_pruned(
    n: int, base: int, phase_bits: int, cache: dict
) -> Counter:
    """Opt-in PUBLIC-ONLY exact identity controlled-U elimination.

    Separate from original stage_arithmetic_count for historical science
    reproducibility. The public modular multiplier b^(2^k) == 1 (mod N)
    makes the entire controlled modular multiplication U_1=I; no private
    order, factors, eigenphase, outcome, or oracle is consulted.
    This is a structural CCX/CX/CSWAP count only; not a native device
    CZ/depth, or a 9-wire scratch elimination.
    """
    if n <= 2 or not (1 < base < n) or math.gcd(base, n) != 1:
        raise ValueError("require public coprime base 1<a<N")
    if phase_bits < 0:
        raise ValueError("phase_bits must be nonnegative")
    total = Counter()
    multiplier = base % n
    for _ in range(phase_bits):
        if multiplier != 1:
            key = (n, multiplier)
            if key not in cache:
                cache[key] = controlled_modmul_count(n, multiplier)
            total += cache[key]
        multiplier = (multiplier * multiplier) % n
    return total


def public_identity_rounds(n: int, base: int, phase_bits: int) -> list[int]:
    """List ONLY the public multiplier=1 rounds, independent of true order."""
    if n <= 2 or not (1 < base < n) or math.gcd(base, n) != 1:
        raise ValueError("require public coprime base 1<a<N")
    if phase_bits < 0:
        raise ValueError("phase_bits must be nonnegative")
    multiplier = base % n
    positions = []
    for k in range(phase_bits):
        if multiplier == 1:
            positions.append(k)
        multiplier = (multiplier * multiplier) % n
    return positions


def architecture_overhead(kind: str, phase_bits: int) -> Counter:
    m = int(phase_bits)
    c = Counter()
    if kind == "wide":
        c["phase_h"] += 2 * m  # preparation + inverse-QFT H
        c["terminal_measure"] += m
        c["qft_controlled_phase"] += m * (m - 1) // 2
        c["qft_swap"] += m // 2
    elif kind == "recycled":
        c["phase_h"] += 2 * m
        c["mid_measure"] += m
        c["reset"] += m
        c["classically_conditioned_phase"] += m * (m - 1) // 2
    else:
        raise ValueError(kind)
    return c


def evaluate_policy(
    *, n: int, base: int, order: int, kind: str,
    start_bits: int, step_bits: int, shots_per_stage: int,
    modmul_cache: dict,
) -> dict:
    bits = stage_schedule(n, start_bits, step_bits)
    width = arithmetic_width(n)
    peak_width = (
        width["recycled_logical_qubits"]
        if kind == "recycled"
        else width["arithmetic_qubits_excluding_phase"] + max(bits)
    )

    reach = 1.0
    totals = Counter()
    expected_rounds = 0.0
    expected_shots = 0.0
    expected_qubit_execution_volume = 0.0
    stage_rows = []

    for m in bits:
        p = per_shot_stage_success(n, order, m)
        fail = (1.0 - p) ** shots_per_stage
        exp_exec = reach * expected_stage_shots(p, shots_per_stage)

        arith = stage_arithmetic_count(n, base, m, modmul_cache)
        overhead = architecture_overhead(kind, m)
        stage_cost = arith + overhead
        for key, value in stage_cost.items():
            totals[key] += exp_exec * value

        expected_rounds += exp_exec * m
        expected_shots += exp_exec
        stage_width = (
            width["recycled_logical_qubits"]
            if kind == "recycled"
            else width["arithmetic_qubits_excluding_phase"] + m
        )
        expected_qubit_execution_volume += exp_exec * stage_width

        stage_rows.append({
            "phase_bits": m,
            "per_shot_success_probability": p,
            "reach_probability": reach,
            "expected_circuit_executions_unconditional": exp_exec,
            "stage_logical_qubits": stage_width,
            "arithmetic_ccx_per_execution": int(arith.get("ccx", 0)),
            "arithmetic_cswap_per_execution": int(arith.get("cswap", 0)),
        })
        reach *= fail

    success = 1.0 - reach
    return {
        "kind": kind,
        "base": int(base),
        "order_validation_only": int(order),
        "stage_bits": bits,
        "shots_per_stage": int(shots_per_stage),
        "peak_logical_qubits": int(peak_width),
        "width_model": width,
        "success_probability_by_cap": float(success),
        "failure_probability_by_cap": float(reach),
        "expected_circuit_executions_per_attempted_session": float(expected_shots),
        "expected_phase_rounds_per_attempted_session": float(expected_rounds),
        "expected_qubit_execution_volume": float(expected_qubit_execution_volume),
        "expected_resources_per_attempted_session": {
            k: float(v) for k, v in sorted(totals.items())
        },
        "expected_resources_per_success_with_session_restarts": {
            k: (float(v) / success if success else None)
            for k, v in sorted(totals.items())
        },
        "stages": stage_rows,
    }


def ratio(num: float, den: float):
    return None if not den else float(num / den)


def validate_case(cfg: dict) -> dict:
    n = int(cfg["N"])
    p = int(cfg["p_validation_only"])
    q = int(cfg["q_validation_only"])
    ell = int(cfg["ell"])
    a = int(cfg["base"])
    b = pow(a, ell, n)
    lam = math.lcm(p - 1, q - 1)
    r0 = multiplicative_order_from_lambda(a, n, lam)
    r1 = multiplicative_order_from_lambda(b, n, lam)

    if b != int(cfg["expected_transformed_base"]):
        raise AssertionError(f"N={n}: transformed base mismatch")
    if (r0, r1) != (
        int(cfg["expected_order"]),
        int(cfg["expected_transformed_order"]),
    ):
        raise AssertionError(f"N={n}: order mismatch {r0}->{r1}")
    if r1 != r0 // math.gcd(r0, ell):
        raise AssertionError(f"N={n}: odd-power order identity failed")

    w0 = factor_witness(a, r0, n)
    w1 = factor_witness(b, r1, n)
    if not w0["factor_success"] or not w1["factor_success"]:
        raise AssertionError(f"N={n}: factor witness failed")

    s0 = power2_chain_shortcut(a, n)
    s1 = power2_chain_shortcut(b, n)
    if s0["factor_found"] or s1["factor_found"]:
        raise AssertionError(f"N={n}: classical shortcut guardrail failed")

    return {
        "N": n,
        "ell": ell,
        "seed_base": a,
        "transformed_base": b,
        "lambda_validation_only": lam,
        "baseline_order_validation_only": r0,
        "transformed_order_validation_only": r1,
        "order_reduction_factor": float(r0 / r1),
        "baseline_factor_witness": w0,
        "transformed_factor_witness": w1,
        "baseline_classical_shortcut": s0,
        "transformed_classical_shortcut": s1,
    }


def run_case(
    key: str, *, start_bits: int, step_bits: int, shots_per_stage: int
) -> dict:
    case = validate_case(CASES[key])
    n = case["N"]
    a = case["seed_base"]
    b = case["transformed_base"]
    r0 = case["baseline_order_validation_only"]
    r1 = case["transformed_order_validation_only"]
    cache = {}

    rows = {}
    for policy, base, order in (
        ("baseline", a, r0),
        ("dark_star", b, r1),
    ):
        for kind in ("wide", "recycled"):
            rows[f"{policy}_{kind}"] = evaluate_policy(
                n=n,
                base=base,
                order=order,
                kind=kind,
                start_bits=start_bits,
                step_bits=step_bits,
                shots_per_stage=shots_per_stage,
                modmul_cache=cache,
            )

    bw = rows["baseline_wide"]
    br = rows["baseline_recycled"]
    dw = rows["dark_star_wide"]
    dr = rows["dark_star_recycled"]

    bccx = br["expected_resources_per_attempted_session"]["ccx"]
    dccx = dr["expected_resources_per_attempted_session"]["ccx"]
    bround = br["expected_phase_rounds_per_attempted_session"]
    dround = dr["expected_phase_rounds_per_attempted_session"]

    comparison = {
        "baseline_wide_to_recycled_peak_width_ratio": ratio(
            br["peak_logical_qubits"], bw["peak_logical_qubits"]
        ),
        "baseline_wide_to_recycled_peak_width_reduction": 1.0 - ratio(
            br["peak_logical_qubits"], bw["peak_logical_qubits"]
        ),
        "dark_star_wide_to_recycled_peak_width_ratio": ratio(
            dr["peak_logical_qubits"], dw["peak_logical_qubits"]
        ),
        "dark_star_wide_to_recycled_peak_width_reduction": 1.0 - ratio(
            dr["peak_logical_qubits"], dw["peak_logical_qubits"]
        ),
        "dark_star_over_baseline_phase_round_ratio": ratio(dround, bround),
        "dark_star_phase_round_reduction": 1.0 - ratio(dround, bround),
        "dark_star_over_baseline_expected_ccx_ratio": ratio(dccx, bccx),
        "dark_star_expected_ccx_reduction": 1.0 - ratio(dccx, bccx),
        "per_phase_round_ccx_ratio_dark_star_over_baseline": ratio(
            ratio(dccx, bccx), ratio(dround, bround)
        ),
        "dark_star_success_probability_delta": (
            dr["success_probability_by_cap"] - br["success_probability_by_cap"]
        ),
        "combined_dark_recycled_vs_baseline_wide_peak_width_ratio": ratio(
            dr["peak_logical_qubits"], bw["peak_logical_qubits"]
        ),
        "combined_dark_recycled_vs_baseline_wide_peak_width_reduction": 1.0 - ratio(
            dr["peak_logical_qubits"], bw["peak_logical_qubits"]
        ),
        "combined_dark_recycled_vs_baseline_wide_expected_ccx_ratio": ratio(
            dccx,
            bw["expected_resources_per_attempted_session"]["ccx"],
        ),
        "combined_dark_recycled_vs_baseline_wide_expected_ccx_reduction": 1.0 - ratio(
            dccx,
            bw["expected_resources_per_attempted_session"]["ccx"],
        ),
    }

    return {
        **case,
        "resource_model": (
            "Analytic exact gate-count mirror of the generic reusable-clean-ancilla "
            "constant-add/modular-multiply construction. Gate count grows polynomially "
            "with work-register bit width; no truth-table/full-state permutation synthesis."
        ),
        "rows": rows,
        "comparison": comparison,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--case", choices=["209", "713", "781", "all"], default="all")
    ap.add_argument("--start-bits", type=int, default=4)
    ap.add_argument("--step-bits", type=int, default=2)
    ap.add_argument("--shots-per-stage", type=int, default=4)
    ap.add_argument(
        "--out",
        type=Path,
        default=Path(
            "results/dark_star_ptp/dark_star_recycled_scalable_arithmetic_audit.json"
        ),
    )
    args = ap.parse_args()

    keys = list(CASES) if args.case == "all" else [args.case]
    out = {
        "experiment": "dark_star_recycled_scalable_arithmetic_audit_v1",
        "script_revision": REV,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "zero_qpu": True,
        "qpu_jobs_submitted": 0,
        "start_bits": args.start_bits,
        "step_bits": args.step_bits,
        "shots_per_stage": args.shots_per_stage,
        "cases": {},
        "claim_boundary": (
            "Polynomial generic reversible-arithmetic resource model plus exact ideal "
            "staged-QPE stopping probabilities. Not a hardware timing/fidelity result, "
            "not an RSA-scale implementation claim, and not an asymptotic Shor speedup."
        ),
    }

    for key in keys:
        out["cases"][key] = run_case(
            key,
            start_bits=args.start_bits,
            step_bits=args.step_bits,
            shots_per_stage=args.shots_per_stage,
        )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(out, indent=2, default=str) + "\n", encoding="utf-8")

    print("===== DARK STAR + RECYCLED SCALABLE-ARITHMETIC SUMMARY =====")
    for key in keys:
        row = out["cases"][key]
        c = row["comparison"]
        bw = row["rows"]["baseline_wide"]
        dr = row["rows"]["dark_star_recycled"]
        print(
            f"N={row['N']} ell={row['ell']} "
            f"order={row['baseline_order_validation_only']}->{row['transformed_order_validation_only']} | "
            f"peak_width baseline-wide->{dr['kind']}={bw['peak_logical_qubits']}->{dr['peak_logical_qubits']} "
            f"({100*c['combined_dark_recycled_vs_baseline_wide_peak_width_reduction']:.2f}% less) | "
            f"phase_rounds dark/base={c['dark_star_over_baseline_phase_round_ratio']:.4f} "
            f"({100*c['dark_star_phase_round_reduction']:.2f}% less) | "
            f"CCX dark/base={c['dark_star_over_baseline_expected_ccx_ratio']:.4f} "
            f"({100*c['dark_star_expected_ccx_reduction']:.2f}% less) | "
            f"per-round_CCX_ratio={c['per_phase_round_ccx_ratio_dark_star_over_baseline']:.4f}"
        )
    print(f"\nwrote {args.out}")
    print("NO QPU JOB SUBMITTED.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
