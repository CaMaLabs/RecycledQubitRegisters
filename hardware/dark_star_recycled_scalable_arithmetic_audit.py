"""Dark Star + recycled-QPE audit with scalable reversible arithmetic.

This zero-QPU audit combines two previously separate project results:

1. public residue-conditioned odd-power order preconditioning (Dark Star), and
2. staged/iterative phase estimation with a one-qubit recycled phase register.

Unlike the small-N full-register truth-table compiler studies, this audit uses
the repository's generic clean-ancilla reversible modular-arithmetic
construction as an *analytic polynomial resource model*.  It mirrors the gate
structure of hardware/ibm_shor_generic_arithmetic_clean_mcx.py without building
multi-million-gate Qiskit circuits.

For each controlled modular multiplication it counts the exact abstract
primitives generated by that construction:
- Toffoli/CCX gates from the reusable clean-ancilla MCX chains;
- controlled-SWAP gates;
- phase-estimation overhead separately.

The circuit constructor/resource counter uses only public N, base and
base^(2^k) mod N.  Validation-only factors and orders are used to generate exact
ideal staged-QPE stopping probabilities and to verify the preregistered scout
cases.  They are never used to skip arithmetic rounds or simplify a multiplier.

This is a resource-model result, not a QPU runtime/fidelity result and not an
asymptotic improvement to Shor's algorithm.
"""
