#!/usr/bin/env python3
"""A32 same-cohort N35 integration: original wheel + true recycled QPE source.

Constructs the actual existing 32-qubit dynamic circuit and checks its
source-level structure; optional exact A23 Quaspy executable is invoked
separately with its own environment. No shot execution or full factor speedup.
"""
import argparse
import importlib.util
import json
from pathlib import Path
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[1]
def load(name,path):
    spec=importlib.util.spec_from_file_location(name,path)
    obj=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(obj)
    return obj

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--a23-script",type=Path)
    p.add_argument("--a23-python",default=sys.executable)
    p.add_argument("--upstream",type=Path)
    p.add_argument("--out",type=Path,default=Path("results/a32_n35_handoff.json"))
    a=p.parse_args()
    gate=load("a24",ROOT/"integrations/darkstar_hybrid/qrr_a24_n35_public_first_gate.py")
    records=[]
    try:
        # Qiskit is optional; if absent we report that explicitly.
        sys.path.insert(0,str(ROOT/"hardware"))
        source=load("qrr_true_source",ROOT/"hardware/qrr_n35_true_recycled_phase_feedforward.py")
        source.configure_original_public_arithmetic()
        for base in (2,8):
            pre=gate.public_preflight(35,base)
            assert pre["factors"]==[5,7]
            circuit,registers,classic,schedule,feedback=source.build_dynamic_source(base,8)
            assert circuit.num_qubits==32 and circuit.num_clbits==8
            assert len(schedule)==8 and circuit.count_ops().get("measure",0)==8
            records.append(dict(n=35,base=base,classical_route=pre["route"],
                classical_factors=pre["factors"],quantum_needed_for_factoring=False,
                counterfactual_circuit_validation_only=True,
                source_logical_qubits=circuit.num_qubits,phase_classical_bits=circuit.num_clbits,
                measurements=circuit.count_ops().get("measure",0),
                resets=circuit.count_ops().get("reset",0),
                source_operations={str(k):int(v) for k,v in circuit.count_ops().items()},
                scheduled_stages=len(schedule),feedback_conditions=len(feedback)))
        source_status="PASS_SOURCE_CONSTRUCTION"
        source_error=None
    except (ImportError,ModuleNotFoundError) as exc:
        source_status="DEPENDENCY_UNAVAILABLE"
        source_error=str(exc)
    except Exception as exc:
        source_status="FAIL_SOURCE_CONSTRUCTION"
        source_error=repr(exc)
    quaspy={"status":"NOT_EXECUTED","reason":"Pass --a23-script, --a23-python and --upstream to run existing Quaspy A23 bridge"}
    if a.a23_script:
        if not a.a23_script.is_file():
            quaspy={"status":"MISSING_SOURCE","path":str(a.a23_script)}
        else:
            cmd=[a.a23_python,str(a.a23_script)]
            if a.upstream:cmd+=["--upstream",str(a.upstream)]
            try:
                r=subprocess.run(cmd,capture_output=True,text=True,timeout=180)
                quaspy={"status":"PASS" if r.returncode==0 and "PASS_EXACT_IDEAL_BRIDGE" in r.stdout else "FAIL",
                  "returncode":r.returncode,"stdout_tail":r.stdout[-4000:],"stderr_tail":r.stderr[-2000:]}
            except Exception as exc:
                quaspy={"status":"ERROR","details":repr(exc)}
    report={"experiment":"A32_REAL_RECYCLED_SOURCE_SAME_N35_HARDWARE_FREE",
      "classical_first":True,"source_status":source_status,"source_error":source_error,
      "quaspy_replay":quaspy,"rows":records,
      "full_end_to_end_shor":False,"qpu_jobs":0,
      "interpretation":"Original dynamic QPE source constructed and compared with classical N35 preflight. A23 exact spectral Quaspy remains separate unless supplied; no shot distribution generated by this circuit and no quantum advantage."}
    a.out.parent.mkdir(parents=True,exist_ok=True)
    a.out.write_text(json.dumps(report,indent=2)+"\n")
    print(json.dumps(report,indent=2))
    return 0 if source_status=="PASS_SOURCE_CONSTRUCTION" and quaspy["status"] not in ("FAIL","ERROR","MISSING_SOURCE") else 1
if __name__=="__main__":raise SystemExit(main())
